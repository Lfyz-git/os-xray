#!/bin/sh
# Build two native FreeBSD pkg packages: xray-tun2socks and os-xray.
# Run inside FreeBSD 15.1 amd64 with opnsense/plugins checked out alongside.
# No installation or migration on any operational firewall.
set -eu

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)
UPSTREAM="${OPNSENSE_PLUGINS_DIR:-$ROOT/opnsense-plugins}"
DEST="${PACKAGE_OUTPUT_DIR:-$ROOT/dist}"
WORK="${TMPDIR:-/tmp}/os-xray-native-build"
PORT="$UPSTREAM/security/xray"
T2S_VERSION="2.7.0"
T2S_SHA256="3ebb747aa83ee3157330beb324bbeaf9a742db6a8d24b9bbc96a4125aaeeeaea"
T2S_URL="https://github.com/xjasonlyu/tun2socks/releases/download/v$T2S_VERSION/tun2socks-freebsd-amd64.zip"

[ "$(uname -s)" = "FreeBSD" ] || { echo "FreeBSD build host required" >&2; exit 1; }
[ "$(uname -m)" = "amd64" ] || { echo "amd64 build required" >&2; exit 1; }
[ -f "$UPSTREAM/Mk/plugins.mk" ] || { echo "Missing upstream opnsense/plugins checkout: $UPSTREAM" >&2; exit 1; }
command -v pkg >/dev/null 2>&1
command -v unzip >/dev/null 2>&1
command -v fetch >/dev/null 2>&1
pkg info -e xray-core || { echo "Install FreeBSD/OPNsense xray-core first" >&2; exit 1; }
pkg info -e php84-curl || { echo "Install php84-curl first" >&2; exit 1; }

mkdir -p "$DEST" "$WORK" "$PORT"
# Use pinned, checksummed upstream release to construct a separate binary
# dependency package, NOT to overwrite FreeBSD or OPNsense-owned executables.
fetch -o "$WORK/tun2socks.zip" "$T2S_URL"
[ "$(sha256 -q "$WORK/tun2socks.zip")" = "$T2S_SHA256" ] || {
    echo "tun2socks SHA256 mismatch" >&2; exit 1;
}
mkdir -p "$WORK/unpack" "$WORK/tun-stage/usr/local/libexec/os-xray"
unzip -oq "$WORK/tun2socks.zip" -d "$WORK/unpack"
TUN=$(find "$WORK/unpack" -type f -name 'tun2socks-freebsd-amd64*' | head -n 1)
[ -n "$TUN" ] || { echo "tun2socks binary missing" >&2; exit 1; }
install -m 0755 "$TUN" "$WORK/tun-stage/usr/local/libexec/os-xray/tun2socks"

cat > "$WORK/tun-manifest" <<EOF
name: xray-tun2socks
version: "$T2S_VERSION"
origin: net/xray-tun2socks
comment: Dedicated tun2socks binary for private os-xray OPNsense plugin
maintainer: N/A
www: https://github.com/xjasonlyu/tun2socks
prefix: /usr/local
licenselogic: single
licenses: [ MIT ]
EOF
printf '/usr/local/libexec/os-xray/tun2socks\n' > "$WORK/tun-plist"
/usr/local/sbin/pkg create -M "$WORK/tun-manifest" -r "$WORK/tun-stage" -p "$WORK/tun-plist" -o "$DEST"
[ -f "$DEST/xray-tun2socks-$T2S_VERSION.pkg" ] || { echo "tun2socks pkg missing" >&2; exit 1; }
pkg add -f "$DEST/xray-tun2socks-$T2S_VERSION.pkg"

# Populate upstream OPNsense plugin build layout; never invoke install.sh.
cp "$ROOT/packaging/native/Makefile" "$PORT/Makefile"
cp "$ROOT/packaging/native/pkg-descr" "$PORT/pkg-descr"
mkdir -p "$PORT/src/etc" "$PORT/src/opnsense/mvc" "$PORT/src/opnsense/service" "$PORT/src/opnsense/scripts"
cp -R "$ROOT/plugin/etc/." "$PORT/src/etc/"
cp -R "$ROOT/plugin/mvc/." "$PORT/src/opnsense/mvc/"
cp -R "$ROOT/plugin/service/." "$PORT/src/opnsense/service/"
cp -R "$ROOT/plugin/scripts/." "$PORT/src/opnsense/scripts/"
chmod 0755 "$PORT/src/etc/rc.syshook.d/start/50-xray"
chmod 0755 "$PORT"/src/opnsense/scripts/Xray/*.php
# Package metadata (including xray-core dependency) and lifecycle hooks are
# generated by the *official* opnsense/plugins Mk/plugins.mk.
make -C "$PORT" package
cp "$PORT"/work/pkg/os-xray-*.pkg "$DEST/"
test -f "$DEST/os-xray-3.3.0.pkg"
pkg info -F "$DEST/os-xray-3.3.0.pkg"
pkg info -F "$DEST/xray-tun2socks-$T2S_VERSION.pkg"
echo "Native packages built in $DEST"
